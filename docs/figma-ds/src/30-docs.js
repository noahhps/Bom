/* Cover and Foundations. Every swatch, bar and card is bound to the variable or
 * style it documents, so the page cannot drift from the tokens. */

async function swatch(varName, label) {
  const f = al("Swatch/" + varName, "VERTICAL", { gap: 6 });
  fixW(f, 132);
  const r = rect("chip", 132, 56, null);
  r.fills = [paint(varName)];
  r.cornerRadius = 6;
  r.strokes = [rawSolid("#000000", 0.08)];
  r.strokeAlign = "INSIDE";
  f.appendChild(r);
  add(f, await txt(label || varName, "UI/XS", "text/primary", { name: "name" }), { wrap: true });
  const css = V[varName].codeSyntax && V[varName].codeSyntax.WEB;
  if (css) add(f, await txt(css, "UI/XS", "text/tertiary", { name: "css" }), { wrap: true });
  return f;
}

function wrapRow(name, width) {
  const row = al(name, "HORIZONTAL", { gap: 16 });
  row.layoutWrap = "WRAP";
  row.counterAxisSpacing = 20;
  fixW(row, width);
  return row;
}

async function foundationSection(page, title, description, content) {
  const sec = figma.createSection();
  sec.name = title;
  page.appendChild(sec);
  const doc = await docFrame(title, description);
  sec.appendChild(doc);
  doc.x = 48;
  doc.y = 72;
  sec.appendChild(content);
  content.x = 500;
  content.y = 72;
  const h = Math.max(doc.y + doc.height, content.y + content.height) + 72;
  sec.resizeWithoutConstraints(Math.max(content.x + content.width + 72, 1200), h);
  sec.x = 0;
  sec.y = nextY(page, h);
  return sec;
}

async function buildFoundations(page) {
  // Semantic colours, by group.
  const groups = {};
  for (const [name] of SEMANTIC) (groups[name.split("/")[0]] = groups[name.split("/")[0]] || []).push(name);
  const colours = al("Color", "VERTICAL", { gap: 28 });
  for (const [group, names] of Object.entries(groups)) {
    colours.appendChild(await txt(group, "Label/Micro", "text/tertiary", { name: "group" }));
    const row = wrapRow(group, 1300);
    for (const n of names) row.appendChild(await swatch(n, n));
    colours.appendChild(row);
  }
  setMode(colours, "teal");
  await foundationSection(
    page,
    "Color",
    `Semantic colours -- what components bind to. The Color collection has a mode per accent (${MODES.map((m) => m.name).join(", ")}); this board is set to ${MODES.find((m) => m.key === "teal") ? "Teal" : "Default"}. Switch any frame's mode to re-theme it, the way theme.js re-themes a conversation.`,
    colours,
  );

  // Every preset, as the primitives theme.js computed.
  const presets = al("Accent presets", "VERTICAL", { gap: 14 });
  const tokens = ["accent", "accent-soft", "field", "wash", "aura-1", "aura-2", "aura-3", "ink", "line"];
  const head = al("head", "HORIZONTAL", { gap: 8 });
  const blank = await txt("", "Label/Micro", "text/tertiary");
  head.appendChild(blank);
  blank.resize(110, blank.height);
  for (const t of tokens) {
    const l = await txt(t, "Label/Micro", "text/tertiary");
    head.appendChild(l);
    l.resize(64, l.height);
  }
  presets.appendChild(head);
  for (const p of DATA.presets) {
    const row = al(p.id, "HORIZONTAL", { gap: 8, align: "CENTER" });
    const name = await txt(p.name, "UI/SM", "text/primary");
    row.appendChild(name);
    name.resize(110, name.height);
    for (const t of tokens) {
      const r = rect(t, 64, 32, null);
      r.fills = [paint(`preset/${p.id}/${t}`)];
      r.cornerRadius = 4;
      r.strokes = [rawSolid("#000000", 0.08)];
      r.strokeAlign = "INSIDE";
      row.appendChild(r);
    }
    presets.appendChild(row);
  }
  await foundationSection(
    page,
    "Accent presets",
    "The ten presets on the swatch row, at the default strength (0.55). Generated by docs/figma-ds/build.sh from lib/theme.js -- rebuild the plugin rather than editing these. Auto mode picks one of these hues from the conversation.",
    presets,
  );

  // Type.
  const type = al("Type", "VERTICAL", { gap: 22 });
  fixW(type, 1100);
  for (const [name, weight, size, lh, track, upper, sizeVar, what] of TEXT_STYLES) {
    if (name === "Display/Cover") continue;
    const row = al(name, "VERTICAL", { gap: 6 });
    add(type, row, { fill: true });
    const css = sizeVar ? ` · var(${TYPE_SCALE.find((t) => t[0] === sizeVar)[2]})` : "";
    add(row, await txt(`${name} — DM Mono ${weight} ${size} / ${lh}%${track ? ` · +${track}%` : ""}${css} — ${what}`, "UI/XS", "text/tertiary"), { wrap: true });
    add(row, await txt(name.startsWith("Label") ? "Answered by" : "Ask me. Task me. The quick brown fox, 0123456789.", name, "text/primary"), { wrap: true });
  }
  await foundationSection(
    page,
    "Typography",
    "One family, DM Mono, at every size -- the app and QuickView render as one product. Seven sizes, each with a role; weight 400 for text, 500 for labels and emphasis.",
    type,
  );

  // Spacing.
  const space = al("Spacing", "VERTICAL", { gap: 8 });
  for (const n of SPACE) {
    const row = al("space/" + n, "HORIZONTAL", { gap: 16, align: "CENTER" });
    const bar = rect("bar", n, 12, "accent/default");
    bar.setBoundVariable("width", V["space/" + n]);
    const label = await txt(`space/${n}`, "UI/XS", "text/secondary");
    row.appendChild(label);
    label.resize(90, label.height);
    row.appendChild(bar);
    space.appendChild(row);
  }
  setMode(space, "teal");
  await foundationSection(page, "Spacing", "The values the stylesheet actually uses, named by size. Components bind padding and gaps to these.", space);

  // Radius and elevation.
  const shapes = al("Shape", "VERTICAL", { gap: 40 });
  const radii = al("radii", "HORIZONTAL", { gap: 24 });
  shapes.appendChild(radii);
  for (const [name, value] of RADII) {
    const card = al(name, "VERTICAL", { gap: 8, align: "CENTER" });
    const r = rect("shape", 72, 72, "surface/field");
    r.strokes = [paint("accent/default")];
    r.strokeWeight = 1.5;
    radius(r, name);
    card.appendChild(r);
    card.appendChild(await txt(`${name} · ${value >= 999 ? "full" : value + "px"}`, "UI/XS", "text/secondary"));
    radii.appendChild(card);
  }
  const effects = al("effects", "HORIZONTAL", { gap: 40, pad: [24, 24, 40, 24], fill: "surface/plate", radius: "radius/row" });
  shapes.appendChild(effects);
  for (const name of ["Elevation/Composer", "Elevation/Composer raised", "Elevation/Window"]) {
    const card = al(name, "VERTICAL", { pad: [16, 16], align: "CENTER", justify: "CENTER", fill: "surface/raised", radius: "radius/composer" });
    fixed(card, 200, 100);
    await card.setEffectStyleIdAsync(ES[name].id);
    card.appendChild(await txt(name, "UI/XS", "text/secondary", { align: "CENTER" }));
    effects.appendChild(card);
  }
  setMode(shapes, "teal");
  await foundationSection(
    page,
    "Shape & elevation",
    "Nearly square is the rule (3px). The composer (16) and QuickView (18) are the rounded exceptions. The only shadows in the system are under the composer and a window.",
    shapes,
  );
}

async function buildCover(page, report) {
  const cover = figma.createFrame();
  cover.name = "Cover";
  cover.resize(1440, 900);
  cover.fills = [paint("surface/sheet")];
  cover.clipsContent = true;
  page.appendChild(cover);
  cover.x = 0;
  cover.y = nextY(page, 900);
  const aura = use("Aura/Sheet");
  cover.appendChild(aura);
  aura.resize(1440, 900);
  const mark = markRect(34, 110);
  cover.appendChild(mark);
  mark.x = 120;
  mark.y = 250;
  const title = await txt("Courier", "Display/Cover", "text/primary");
  cover.appendChild(title);
  title.x = 120;
  title.y = 390;
  const sub = await txt("Design system — tokens, components and screens, synced from client/src.", "UI/MD Prose", "text/secondary");
  cover.appendChild(sub);
  sub.x = 124;
  sub.y = 510;
  const meta = await txt(`v1 · built ${new Date().toISOString().slice(0, 10)} · DM Mono · ${MODES.length} accent mode(s)`, "Label/Micro", "text/tertiary");
  cover.appendChild(meta);
  meta.x = 124;
  meta.y = 560;
  setMode(cover, "teal");

  const guide = await docFrame("Getting started", "How this file is put together, and how to keep it honest.", [
    "Foundations: Primitives (raw, hidden) → Color (what components bind to, one mode per accent) · QuickView · Dimension. Text and effect styles are DM Mono and the composer/window shadows.",
    "Components: atoms first. Variants for states, properties for text, booleans for optional parts, Icon swaps for glyphs.",
    "Patterns: whole screens assembled only from instances. Change a component and the screens follow.",
    "Theming: select a frame → Appearance → Color mode. The rail is usually set to the app-wide accent and the window to the conversation's.",
    "Keeping it in sync: edit docs/figma-ds/src, run build.sh (it recomputes the palettes from lib/theme.js), and run the plugin in a fresh file.",
  ]);
  page.appendChild(guide);
  guide.x = 1520;
  guide.y = cover.y + 40;
  if (report.length) {
    for (const line of report) add(guide, await txt("⚠ " + line, "UI/SM", "text/warn", { name: "note" }), { wrap: true });
  }
}
